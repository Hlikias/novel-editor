# ---------------- 查询 ----------------
def lookup_idiom(word: str) -> str | None:
    w = (word or "").strip()
    data = get_idioms()
    item = data.get(w)
    if item is None:
        hits = [k for k in data if w in k or k in w]
        if len(hits) == 1:
            item = data[hits[0]]
            w = hits[0]
        elif len(hits) > 1:
            lines = ["可能要找："]
            lines += [f"  {k}：{data[k]['explain']}" for k in hits[:8]]
            return "\n".join(lines)
        else:
            return None
    lines = [f"【{w}】"]
    if item.get("pinyin"):
        lines.append(f"拼音：{item['pinyin']}")
    if item.get("explain"):
        lines.append(f"释义：{item['explain']}")
    if item.get("origin"):
        lines.append(f"出处：{item['origin']}")
    return "\n".join(lines)


def lookup_xiehouyu(word: str) -> str | None:
    w = (word or "").strip()
    data = get_xiehouyu()
    if w in data:
        return f"{w} —— {data[w]}"
    hits = [k for k in data if w in k or k in w]
    if not hits:
        return None
    # 输入是某词条的前缀 → 直接返回最完整的那个
    prefix = [k for k in hits if k.startswith(w) and len(k) > len(w)]
    if prefix:
        k = max(prefix, key=len)
        return f"{k} —— {data[k]}"
    if len(hits) == 1:
        k = hits[0]
        return f"{k} —— {data[k]}"
    return "可能要找：\n" + "\n".join(f"  {k} —— {data[k]}" for k in hits[:8])


def lookup_slang(word: str) -> str | None:
    w = (word or "").strip().upper()
    data = get_slang()
    if w in data:
        return f"{w}：{data[w]}"
    hits = [k for k in data if w in k or w in k.lower()]
    if len(hits) == 1:
        k = hits[0]
        return f"{k}：{data[k]}"
    if len(hits) > 1:
        return "可能要找：\n" + "\n".join(f"  {k}：{data[k]}" for k in hits[:8])
    return None


def lookup_saying(word: str) -> str | None:
    """俗语/谚语查询：命中返回"俗语 + 释义"，未命中返回 None。"""
    w = (word or "").strip()
    data = get_sayings()
    if w in data:
        return f"{w}——{data[w]}"
    hits = [k for k in data if w in k or k in w]
    if not hits:
        return None
    # 输入是某词条的前缀 → 直接返回最完整的那个（如"三十年河东"→完整句）
    prefix = [k for k in hits if k.startswith(w) and len(k) > len(w)]
    if prefix:
        k = max(prefix, key=len)
        return f"{k}——{data[k]}"
    if len(hits) == 1:
        k = hits[0]
        return f"{k}——{data[k]}"
    return "可能要找：\n" + "\n".join(f"  {k}——{data[k]}" for k in hits[:8])


def random_quote() -> str:
    text, author, source = random.choice(get_quotes())
    out = text
    if author:
        out += f"\n—— {author}{'《' + source + '》' if source else ''}"
    return out


# ---------------- 检索系统 ----------------
def search_all(keyword: str, limit_per_type: int = 40) -> list:
    """跨类别检索本地词库。
    返回 [{"type": "成语|歇后语|网络用语|金句", "word": ..., "text": ...}]"""
    kw = (keyword or "").strip()
    if not kw:
        return []
    out = []
    idioms = get_idioms()
    for w, item in idioms.items():
        if kw in w or w in kw or kw in item.get("explain", ""):
            out.append({"type": "成语", "word": w, "text": lookup_idiom(w)})
            if len([x for x in out if x["type"] == "成语"]) >= limit_per_type:
                break
    xhy = get_xiehouyu()
    for w, a in xhy.items():
        if kw in w or w in kw or kw in a:
            out.append({"type": "歇后语", "word": w, "text": f"{w} —— {a}"})
            if len([x for x in out if x["type"] == "歇后语"]) >= limit_per_type:
                break
    slang = get_slang()
    for w, d in slang.items():
        if kw in w or kw in d or kw.upper() in w.upper():
            out.append({"type": "网络用语", "word": w, "text": f"{w}：{d}"})
            if len([x for x in out if x["type"] == "网络用语"]) >= limit_per_type:
                break
    saying = get_sayings()
    for w, d in saying.items():
        if kw in w or kw in d:
            out.append({"type": "俗语", "word": w[:14], "text": f"{w}——{d}"})
            if len([x for x in out if x["type"] == "俗语"]) >= limit_per_type:
                break
    for text, author, source in get_quotes():
        if kw in text or kw in author:
            t = f"{text}\n—— {author}{'《' + source + '》' if source else ''}"
            out.append({"type": "金句", "word": text[:16], "text": t})
            if len([x for x in out if x["type"] == "金句"]) >= limit_per_type:
                break
    return out
