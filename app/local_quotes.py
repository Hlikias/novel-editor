# ---------------- 外部词库加载（实现"全收录"） ----------------
def _load_external():
    """合并 ~/.novel_editor/data/ 下的词库 JSON 到内置数据。"""
    merged = {"idioms": dict(IDIOMS), "xiehouyu": dict(XIEHOUYU),
              "slang": dict(SLANG), "saying": dict(SAYINGS), "quotes": list(QUOTES)}
    try:
        os.makedirs(USER_DATA_DIR, exist_ok=True)
        for fname, key in (("idioms.json", "idioms"), ("xiehouyu.json", "xiehouyu"),
                           ("slang.json", "slang"), ("saying.json", "saying"),
                           ("quotes.json", "quotes")):
            path = os.path.join(USER_DATA_DIR, fname)
            if not os.path.exists(path):
                continue
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            if key == "quotes":
                if isinstance(data, list):
                    merged["quotes"].extend(
                        (str(x.get("text", "")), str(x.get("author", "")),
                         str(x.get("source", ""))) for x in data)
            elif isinstance(data, dict):
                merged[key].update(data)
    except Exception:  # noqa: BLE001
        pass
    return merged


